"""
Учит QUERY REFINER искать любую марку, а не только те, что уже есть в словаре.

Что случилось 02.10.2026: на запрос «dodge ram trx» уточнитель ответил
«В реестре только Tesla, Dodge Ram TRX отсутствует» и остановил поиск. Словарь
реестра собирается из прошлых поисков, а искали мы одну Tesla, — и уточнитель
принял след прежних запросов за границу системы, хотя в промпте было сказано,
что словарь — подсказка. Поиск по bid.cars при этом умеет любую марку.

Правки в системном промпте узла:
  1. словарь — подсказка по написанию, его пустота не причина для clarify;
  2. громкие имена других марок — версии: «RAM 1500, TRX», «Ford F-150, Raptor»
     (так лоты названы на bid.cars, проверено 02.10.2026);
  3. trim_as_model срабатывает, только когда модель нельзя вывести из версии;
  4. пример с пикапом.

Каждая правка — замена точного куска текста. Кусок не найден — скрипт падает,
а не публикует наполовину исправленный промпт. Повторный запуск ничего не
меняет и выходит с кодом 2 (как inject-lessons.py).

Запуск:
  python patch-refiner-any-make.py <граф.json> <куда.json>

Модель узла меняет set-models.py, публикация — publish-graph.py.
"""

import json
import sys

TITLE = "QUERY REFINER"
MARK = "Отсутствие марки или модели в словаре НИКОГДА не причина"

EDITS = [
    # 1. Словарь — не граница системы
    (
        """Словарь — подсказка, а не полный каталог: покрытие реестра неполное, и
отсутствие модели в словаре не значит, что её нет на bid.cars. Если
марка и модель названы правильными словами, ищи, даже когда в словаре
их нет.""",
        """Словарь — подсказка по написанию, а не список того, что BRONVERA умеет
искать. В него попадают только лоты из прошлых поисков, поэтому в нём
может оказаться одна-единственная марка: это след прежних запросов, а не
ограничение системы. BRONVERA ищет на bid.cars ЛЮБУЮ марку и модель —
поиск каждый раз идёт на площадку заново.

Отсутствие марки или модели в словаре НИКОГДА не причина для "clarify".
Марки нет в словаре, но такая машина существует — status "ok", а названия
пиши так, как их пишут на аукционах США. Не говори человеку, что «в
реестре только Tesla» или что машины «нет в открытых торгах»: ты этого не
знаешь, это выяснит поиск.""",
    ),
    # 2. Версии у других марок
    (
        """Комплектации всегда идут в поле trims, никогда в models. Если человек
назвал только комплектацию, а модель не назвал, — модель придётся
спросить: у Model S и Model X бывают разные версии, и поиск по всем
моделям марки вернул бы не то, что человек просил.""",
        """Комплектации всегда идут в поле trims, никогда в models. Если человек
назвал только комплектацию, а модель не назвал, — модель придётся
спросить: у Model S и Model X бывают разные версии, и поиск по всем
моделям марки вернул бы не то, что человек просил.

То же у других марок: громкое имя часто оказывается версией. На bid.cars
лоты названы «2022 RAM 1500, TRX», «2020 Ford F-150, Raptor», поэтому:
— "Ram TRX", "Dodge Ram TRX" → make "RAM", models ["1500"], trims ["TRX"]
— "Ford Raptor", "F-150 Raptor" → make "Ford", models ["F-150"], trims ["Raptor"]
— "Ranger Raptor", "Bronco Raptor" → models ["Ranger"] / ["Bronco"], trims ["Raptor"]
Пикапы Ram с 2010 года — отдельная марка RAM, не Dodge: в make пиши "RAM",
даже если человек сказал "Dodge Ram".

Когда версия однозначно указывает на модель (TRX бывает только у RAM 1500,
"Ford Raptor" без уточнения — это F-150), модель не спрашивай: подставь
сам и скажи об этом в "understood".""",
    ),
    # 3. trim_as_model — только когда модель не вывести
    (
        """2. trim_as_model — названа комплектация, а модель нет (наш случай
   "Tesla 100D, P100D, Plaid").""",
        """2. trim_as_model — названа комплектация, а модель нет и вывести её из
   комплектации нельзя (наш случай "Tesla 100D, P100D, Plaid": такие
   версии есть и у Model S, и у Model X).""",
    ),
    # 4. Пример с пикапом
    (
        """Запрос: "Toyota Camry 2018 года на ходу до $6000\"""",
        """Запрос: "dodge ram trx"

{
  "status": "ok",
  "understood": "RAM 1500 в версии TRX (с 2010 года Ram — отдельная марка, не Dodge)",
  "filters": {"make": "RAM", "models": ["1500"], "trims": ["TRX"], "maxResults": 20, "maxPages": 1},
  "warnings": [{"code": "non_ev", "title": "Это не электромобиль", "detail": "Расчёт ввоза в Беларусь настроен для электромобилей: для бензиновых машин пошлина и НДС другие, и выгодность будет предварительной"}],
  "summary": "",
  "reasons": [],
  "suggestions": []
}

Запрос: "Toyota Camry 2018 года на ходу до $6000\"""",
    ),
]

if len(sys.argv) < 3:
    raise SystemExit(__doc__)

source, target = sys.argv[1], sys.argv[2]
graph = json.load(open(source))

nodes = [n for n in graph["nodes"] if n["data"].get("type") == "llm" and n["data"].get("title") == TITLE]
if len(nodes) != 1:
    raise SystemExit(f"узлов «{TITLE}» в графе: {len(nodes)}, нужен ровно один")

prompt = nodes[0]["data"]["prompt_template"][0]
text = prompt.get("text") or ""

if MARK in text:
    print(f"{TITLE}: правка уже на месте — менять нечего")
    raise SystemExit(2)

before = len(text)
for index, (old, new) in enumerate(EDITS, 1):
    if text.count(old) != 1:
        raise SystemExit(f"правка {index}: кусок найден {text.count(old)} раз вместо одного — промпт изменился, сверь с agents/prompts/query-refiner.md")
    text = text.replace(old, new)

prompt["text"] = text
json.dump(graph, open(target, "w"), ensure_ascii=False)

print(f"{TITLE}: правок {len(EDITS)}, промпт {before} → {len(text)} символов")
print(f"всего узлов: {len(graph['nodes'])} | рёбер: {len(graph['edges'])}")
print(f"записано: {target}")
